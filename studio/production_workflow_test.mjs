import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, symlinkSync } from 'node:fs';
import { join } from 'node:path';
import { homedir, tmpdir } from 'node:os';
import { once } from 'node:events';
import { createEpisodeChecklist, mergeEpisodeChecklist, updateEpisodeChecklistItem } from './episode_checklist.mjs';
import { buildProductionWorkflow, loadWorkflowChecklist, saveWorkflowItem, workflowHandoff } from './production_workflow.mjs';
import { createStudioServer } from './server.mjs';
const dir = mkdtempSync(join(tmpdir(), 'eaol-workflow-'));
let server;
try {
  const episode = { slug: 'trial', source_name: 'Trial', intake: { sources: [] } };
  let old = createEpisodeChecklist({ slug:'trial' });
  old.items = old.items.filter(i => !i.id.startsWith('production_cta'));
  old = updateEpisodeChecklistItem(old, 'production_proxy', { status:'complete', notes:'Exact v2 accepted separately', owner:'Host 2' });
  const merged = mergeEpisodeChecklist(old, { slug:'trial' });
  assert.equal(merged.items.find(i=>i.id==='production_proxy').status,'complete');
  assert.equal(merged.items.find(i=>i.id==='production_proxy').owner,'Host 2');
  assert.equal(merged.items.find(i=>i.id==='production_cta_early').status,'todo');
  merged.items.push({id:'custom_production',phase:'production',title:'Custom lens check',status:'todo',owner:'Host 2'});
  const state = buildProductionWorkflow(episode, merged, { display_name:'Host 2' });
  assert.equal(new Set(state.steps.flatMap(s=>s.items.map(i=>i.id))).size, merged.items.length);
  assert.equal(state.steps.flatMap(s=>s.items).length,merged.items.length, 'each checkpoint appears once');
  assert.throws(()=>saveWorkflowItem(dir,merged,'production_proxy',{revision:state.revision,status:'complete',notes:''},state), /Add the version/);
  assert.throws(()=>saveWorkflowItem(dir,merged,'production_proxy',{revision:'old',status:'todo',notes:''},state), /changed/);
  assert.throws(()=>saveWorkflowItem(dir,merged,'production_proxy',{revision:state.revision,status:'complete',notes:'review v3'}, {...state,operator:null}), /operator/);
  const updated = saveWorkflowItem(dir,merged,'production_camera_restarts',{revision:state.revision,status:'blocked',notes:'v3 21–26 seconds: speech clipped; picture okay',owner:'Host 2'},state);
  const reopened = loadWorkflowChecklist(dir,episode);
  assert.equal(reopened.items.find(i=>i.id==='production_camera_restarts').notes,'v3 21–26 seconds: speech clipped; picture okay');
  assert.equal(reopened.items.find(i=>i.id==='production_camera_restarts').recorded_by,'Host 2');
  assert.notEqual(buildProductionWorkflow(episode,updated,{display_name:'Host 2'}).revision,state.revision);
  const recovered = buildProductionWorkflow({...episode,recovery:{staleInputs:['camera'],draftFingerprint:'x'}},merged,null);
  assert.deepEqual(recovered.media,[], 'stale source prevents playback shortcuts');
  assert.ok(recovered.blockers.some(b=>b.includes('recovery map')));
  assert.equal(recovered.steps.find(s=>s.id==='social').target,'social-workspace');
  assert.ok(workflowHandoff(recovered).includes('does not') || workflowHandoff(recovered).includes('do not'));
  assert.ok(!workflowHandoff(recovered).includes(homedir()), 'generated instructions carry no machine-specific paths');

  const workRoot=join(dir,'work'),epDir=join(workRoot,'trial');mkdirSync(epDir,{recursive:true});
  writeFileSync(join(epDir,'meta.json'),JSON.stringify({source:join(epDir,'missing.mp4'),duration_sec:12}));
  server=createStudioServer({workRoot});server.listen(0,'127.0.0.1');await once(server,'listening');
  const base=`http://127.0.0.1:${server.address().port}`;
  const request=async(path,method='GET',body)=>{const r=await fetch(base+path,{method,headers:{'content-type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,body:await r.json()};};
  let result=await request('/api/episodes/trial/production-workflow');assert.equal(result.status,200);
  const url='/api/episodes/trial/production-workflow/delivery_release_copy';
  let patch={revision:result.body.revision,status:'complete',notes:'Test record only'};
  assert.equal((await request(url,'PUT',patch)).status,400);
  await request('/api/operator','PUT',{operator_id:'host_2'});
  result=await request('/api/episodes/trial/production-workflow');patch.revision=result.body.revision;
  const saved=await request(url,'PUT',patch);assert.equal(saved.status,200, JSON.stringify(saved.body));
  assert.equal((await request(url,'PUT',patch)).status,400,'concurrent stale write rejected');
  result=await request('/api/episodes/trial/production-workflow');
  assert.equal(result.body.steps.find(s=>s.id==='release').items.find(i=>i.id==='delivery_publish').status,'todo', 'a release-copy note never completes publication approval');
  const handoff=await fetch(base+'/api/episodes/trial/production-workflow/handoff');assert.equal(handoff.status,200);assert.match(handoff.headers.get('content-disposition'),/attachment/);
  assert.ok((await handoff.text()).includes('Host 2'));
  const episodeReload=await request('/api/episodes/trial');
  assert.equal(episodeReload.body.episode.episode_checklist.items.find(i=>i.id==='delivery_release_copy').status,'complete', 'same checklist used by old and new UI');
  assert.ok(!episodeReload.body.episode.episode_render,'progress must never create production artifacts');
  const outside=join(dir,'outside');mkdirSync(outside);symlinkSync(outside,join(workRoot,'escaped'));
  assert.equal((await request('/api/episodes/escaped/production-workflow')).status,400);
  console.log('PASS template migration, complete step coverage, durable notes, named operator, stale-write rejection, source guards, shared checklist, release separation, path confinement, and no fabricated approvals');
} finally { if(server) await new Promise(resolve=>server.close(resolve)); rmSync(dir,{recursive:true,force:true}); }
